/**
 * `expo-ui-agents`, the `@mrmeg/expo-ui` bin that writes the installed @mrmeg
 * packages' docs index into an app's AGENTS.md.
 *
 * Each case runs the CLI in a throwaway project directory with a fake
 * `node_modules` (a package.json, optionally an `llms.txt` and doc files, per
 * package) and a consumer-style AGENTS.md. The size budget runs against the real
 * workspace `llms.txt` files, because those are what lands in a consumer's
 * context.
 */
import { spawnSync } from "child_process";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "fs";
import { tmpdir } from "os";
import { dirname, join } from "path";

const root = join(__dirname, "..", "..");
const cli = join(root, "packages", "ui", "bin", "expo-ui-agents.mjs");

const START = "<!-- @mrmeg/packages:start -->";
const END = "<!-- @mrmeg/packages:end -->";

const UI = "@mrmeg/expo-ui";
const MEDIA = "@mrmeg/expo-media";
const PURCHASES = "@mrmeg/expo-purchases";
const LINT = "@mrmeg/eslint-plugin-expo-ui";

type Result = { status: number; stdout: string; stderr: string; output: string };

let project: string;

function agents(args: string[] = []): Result {
  const result = spawnSync("node", [cli, ...args], { cwd: project, encoding: "utf8" });
  const stdout = result.stdout ?? "";
  const stderr = result.stderr ?? "";
  return { status: result.status ?? 1, stdout, stderr, output: `${stdout}${stderr}` };
}

const write = (path: string, content: string) => {
  mkdirSync(dirname(join(project, path)), { recursive: true });
  writeFileSync(join(project, path), content);
};
const read = (path: string) => readFileSync(join(project, path), "utf8");
const exists = (path: string) => existsSync(join(project, path));

/** The app's package.json: `deps` as dependencies, `devDeps` as devDependencies. */
const writeManifest = (deps: string[], devDeps: string[] = []) =>
  write(
    "package.json",
    JSON.stringify({
      name: "consumer",
      dependencies: Object.fromEntries(deps.map((name) => [name, "*"])),
      devDependencies: Object.fromEntries(devDeps.map((name) => [name, "*"])),
    })
  );

type InstallOptions = { version?: string; llms?: string | null; docs?: string[] };

/** A fake installed package, replacing any earlier one. `llms: null` ships no llms.txt. */
function install(name: string, { version = "1.2.3", llms, docs = [] }: InstallOptions = {}) {
  const dir = `node_modules/${name}`;
  rmSync(join(project, dir), { recursive: true, force: true });
  write(`${dir}/package.json`, JSON.stringify({ name, version }));
  const body = llms === undefined ? `# ${name}\n\nRules for ${name} v${version}.\n` : llms;
  if (body !== null) write(`${dir}/llms.txt`, body);
  for (const doc of docs) write(`${dir}/${doc}`, `# ${doc}\n`);
}

const sectionOf = (text: string) => text.slice(text.indexOf(START), text.indexOf(END) + END.length);
const SECTION_NOTE = "Generated by `expo-ui-agents`; edit the packages, not this block.";

const CONVEX = [
  "<!-- convex-ai-start -->",
  "",
  "This project uses [Convex](https://convex.dev) as its backend.",
  "",
  "<!-- convex-ai-end -->",
].join("\n");
const NOTES = "## Project Notes\n\n- Install with `bun install`.";
const WORKFLOW = [
  "## Agent Workflow",
  "",
  "<!-- agent-framework:v10 -->",
  "",
  "Use this workflow only for planned work.",
  "",
].join("\n");
const CONSUMER_HEAD = `# UI Conventions\n\nRead the package docs.\n\n${CONVEX}\n\n${NOTES}\n\n\n`;
const CONSUMER = `${CONSUMER_HEAD}${WORKFLOW}`;

beforeEach(() => {
  project = mkdtempSync(join(tmpdir(), "expo-ui-agents-test-"));
  writeManifest([UI]);
  install(UI, { version: "0.9.0", docs: ["LLM_USAGE.md"] });
});

afterEach(() => {
  rmSync(project, { recursive: true, force: true });
});

describe("expo-ui-agents placement", () => {
  it("inserts the section immediately before ## Agent Workflow", () => {
    write("AGENTS.md", CONSUMER);

    const result = agents();
    expect(result.status).toBe(0);
    expect(result.stdout).toContain("Wrote AGENTS.md (@mrmeg/expo-ui@0.9.0).");

    const written = read("AGENTS.md");
    const section = sectionOf(written);
    expect(written).toBe(`${CONSUMER_HEAD}${section}\n\n${WORKFLOW}`);
  });

  it("starts the block after a blank line when the heading follows text directly", () => {
    write("AGENTS.md", "# Notes\n## Agent Workflow\nbody\n");

    expect(agents().status).toBe(0);

    const written = read("AGENTS.md");
    expect(written).toBe(`# Notes\n\n${sectionOf(written)}\n\n## Agent Workflow\nbody\n`);
  });

  it("inserts before a workflow heading at the very top of the file", () => {
    write("AGENTS.md", "## Agent Workflow\nbody\n");

    expect(agents().status).toBe(0);

    const written = read("AGENTS.md");
    expect(written).toBe(`${sectionOf(written)}\n\n## Agent Workflow\nbody\n`);
  });

  it("appends when there is no workflow section", () => {
    const original = `# UI Conventions\n\n${CONVEX}\n\n${NOTES}\n`;
    write("AGENTS.md", original);

    expect(agents().status).toBe(0);

    const written = read("AGENTS.md");
    expect(written).toBe(`${original}\n${sectionOf(written)}\n`);
  });

  it("appends to a file with no trailing newline without altering its last line", () => {
    const original = "# UI Conventions\n\nLast line, no newline";
    write("AGENTS.md", original);

    expect(agents().status).toBe(0);

    const written = read("AGENTS.md");
    expect(written.startsWith(original)).toBe(true);
    expect(written).toBe(`${original}\n\n${sectionOf(written)}\n`);
    expect(agents(["--check"]).status).toBe(0);
  });

  it("does not stack a second blank line when the file already ends with one", () => {
    const original = "# UI Conventions\n\n";
    write("AGENTS.md", original);

    expect(agents().status).toBe(0);

    const written = read("AGENTS.md");
    expect(written).toBe(`${original}${sectionOf(written)}\n`);
  });

  it("does not take a ## Agent Workflow heading inside a fenced code block", () => {
    const original = [
      "# Conventions",
      "",
      "Example of the heading another tool writes:",
      "",
      "```md",
      "## Agent Workflow",
      "```",
      "",
      "~~~",
      "## Agent Workflow",
      "~~~",
      "",
      "",
    ].join("\n");
    write("AGENTS.md", `${original}${WORKFLOW}`);

    expect(agents().status).toBe(0);

    const written = read("AGENTS.md");
    expect(written).toBe(`${original}${sectionOf(written)}\n\n${WORKFLOW}`);
  });

  it("appends when the only ## Agent Workflow heading is fenced", () => {
    const original = "# Conventions\n\n```md\n## Agent Workflow\n```\n";
    write("AGENTS.md", original);

    expect(agents().status).toBe(0);

    const written = read("AGENTS.md");
    expect(written).toBe(`${original}\n${sectionOf(written)}\n`);
  });

  it("creates AGENTS.md when it is absent", () => {
    expect(exists("AGENTS.md")).toBe(false);

    const result = agents();
    expect(result.status).toBe(0);
    expect(result.stdout).toContain("Wrote AGENTS.md");

    const written = read("AGENTS.md");
    expect(written.startsWith(`${START}\n## @mrmeg packages\n`)).toBe(true);
    expect(written.endsWith(`${END}\n`)).toBe(true);
    expect(agents(["--check"]).status).toBe(0);
  });

  it("honors --file and creates its directory", () => {
    expect(agents(["--file", "docs/agents/AGENTS.md"]).status).toBe(0);
    expect(read("docs/agents/AGENTS.md")).toContain(START);
    expect(exists("AGENTS.md")).toBe(false);
    expect(agents(["--file=docs/agents/AGENTS.md", "--check"]).status).toBe(0);
  });
});

describe("expo-ui-agents refresh", () => {
  it("replaces the marked block in place and is idempotent", () => {
    write("AGENTS.md", CONSUMER);
    expect(agents().status).toBe(0);
    const first = read("AGENTS.md");

    const again = agents();
    expect(again.status).toBe(0);
    expect(again.stdout).toContain("AGENTS.md already up to date");
    expect(read("AGENTS.md")).toBe(first);

    // A package upgrade changes the section; nothing outside the markers moves.
    install(UI, { version: "0.10.0", docs: ["LLM_USAGE.md"] });
    const upgraded = agents();
    expect(upgraded.status).toBe(0);
    expect(upgraded.stdout).toContain("Wrote AGENTS.md (@mrmeg/expo-ui@0.10.0).");

    const second = read("AGENTS.md");
    expect(second).not.toBe(first);
    expect(sectionOf(second)).toContain("Installed: @mrmeg/expo-ui@0.10.0");
    expect(sectionOf(second)).not.toContain("0.9.0");
    expect(second).toBe(`${CONSUMER_HEAD}${sectionOf(second)}\n\n${WORKFLOW}`);

    expect(agents().stdout).toContain("already up to date");
    expect(read("AGENTS.md")).toBe(second);
  });

  it("replaces a block the user moved, leaving the text around it alone", () => {
    const before = "# Top\n\nIntro.\n\n";
    const after = "\n\n## Later\n\nText.\n";
    write("AGENTS.md", `${before}${START}\nstale content\n${END}${after}`);

    expect(agents().status).toBe(0);

    const written = read("AGENTS.md");
    expect(written).toBe(`${before}${sectionOf(written)}${after}`);
    expect(sectionOf(written)).toContain("Installed: @mrmeg/expo-ui@0.9.0");
  });

  it("leaves the Convex block and the workflow section byte-identical", () => {
    write("AGENTS.md", CONSUMER);
    install(MEDIA, { version: "0.7.0" });
    writeManifest([UI, MEDIA]);

    expect(agents().status).toBe(0);
    install(UI, { version: "0.11.0", docs: ["LLM_USAGE.md"] });
    expect(agents().status).toBe(0);

    const written = read("AGENTS.md");
    expect(written).toContain(CONVEX);
    expect(written.endsWith(WORKFLOW)).toBe(true);
    // Take the block and its one separating blank line away: the original is back.
    expect(written.replace(`${sectionOf(written)}\n\n`, "")).toBe(CONSUMER);
  });

  it("leaves CRLF content outside the markers byte-identical", () => {
    const original = CONSUMER.replace(/\n/g, "\r\n");
    write("AGENTS.md", original);

    expect(agents().status).toBe(0);
    const first = read("AGENTS.md");
    // The block follows the file's line breaks, so the file stays consistently CRLF.
    expect(first.replace(/\r\n/g, "")).not.toContain("\n");
    expect(first.replace(sectionOf(first) + "\r\n\r\n", "")).toBe(original);
    expect(agents(["--check"]).status).toBe(0);

    expect(agents().stdout).toContain("already up to date");
    expect(read("AGENTS.md")).toBe(first);

    install(UI, { version: "0.12.0", docs: ["LLM_USAGE.md"] });
    expect(agents().status).toBe(0);
    const upgraded = read("AGENTS.md");
    expect(upgraded.replace(sectionOf(upgraded) + "\r\n\r\n", "")).toBe(original);
  });

  it("appends to a CRLF file with CRLF separators", () => {
    const original = "# Top\r\n\r\nText";
    write("AGENTS.md", original);

    expect(agents().status).toBe(0);

    const written = read("AGENTS.md");
    expect(written).toBe(`${original}\r\n\r\n${sectionOf(written)}\r\n`);
    expect(written.replace(/\r\n/g, "")).not.toContain("\n");
  });

  it("treats a section whose line breaks were converted to CRLF as fresh", () => {
    expect(agents().status).toBe(0);
    write("AGENTS.md", read("AGENTS.md").replace(/\n/g, "\r\n"));

    expect(agents(["--check"]).status).toBe(0);
  });

  it("is deterministic: no absolute paths, dates, or machine state in the section", () => {
    expect(agents().status).toBe(0);
    const first = read("AGENTS.md");

    rmSync(join(project, "AGENTS.md"));
    expect(agents().status).toBe(0);
    expect(read("AGENTS.md")).toBe(first);

    expect(first).not.toContain(project);
    expect(first).not.toMatch(/\b20\d\d-\d\d-\d\d\b/);
    expect(first).toContain("`node_modules/@mrmeg/expo-ui/LLM_USAGE.md`");
  });

  it("refuses a file with unbalanced or repeated markers and writes nothing", () => {
    const cases: Array<[string, string]> = [
      ["start without end", `# Top\n\n${START}\nold\n`],
      ["end without start", `# Top\n\nold\n${END}\n`],
      ["end before start", `${END}\n\n${START}\n`],
      ["two blocks", `${START}\na\n${END}\n\n${START}\nb\n${END}\n`],
    ];
    for (const [name, content] of cases) {
      write("AGENTS.md", content);
      for (const args of [[], ["--check"]]) {
        const result = agents(args);
        expect({ name, args, status: result.status }).toEqual({ name, args, status: 1 });
        expect(result.output).toContain("marker line(s)");
      }
      expect(read("AGENTS.md")).toBe(content);
    }
  });
});

describe("expo-ui-agents section content", () => {
  it("lists only installed packages, in a stable order, and warns about the rest", () => {
    // Listed in reverse order; media is listed but not installed; purchases is
    // installed but not listed; lint is a devDependency.
    writeManifest([MEDIA, UI], [LINT]);
    install(LINT, { version: "0.1.0", llms: null, docs: ["README.md"] });
    install(PURCHASES, { version: "0.1.0" });

    const result = agents();
    expect(result.status).toBe(0);
    expect(result.stderr).toContain("@mrmeg/expo-media is listed in package.json but not installed");

    const section = sectionOf(read("AGENTS.md"));
    expect(section).toContain(`Installed: ${UI}@0.9.0, ${LINT}@0.1.0\n`);
    expect(section).not.toContain("### @mrmeg/expo-media");
    expect(section).not.toContain("### @mrmeg/expo-purchases");
    expect(section.indexOf(`### ${UI}`)).toBeGreaterThan(-1);
    expect(section.indexOf(`### ${UI}`)).toBeLessThan(section.indexOf(`### ${LINT}`));
  });

  it("orders all four packages the same way however package.json lists them", () => {
    for (const name of [UI, MEDIA, PURCHASES, LINT]) install(name, { version: "2.0.0" });
    writeManifest([LINT, PURCHASES], [MEDIA, UI]);

    expect(agents().status).toBe(0);
    expect(sectionOf(read("AGENTS.md"))).toContain(`Installed: ${UI}@2.0.0, ${MEDIA}@2.0.0, ${PURCHASES}@2.0.0, ${LINT}@2.0.0\n`);
  });

  it("inlines each llms.txt without its H1, under a ### heading with the version", () => {
    install(UI, { version: "0.9.0", llms: "# @mrmeg/expo-ui\n\nFirst rule.\n\n- a list item\n\n\n" });

    expect(agents().status).toBe(0);

    const section = sectionOf(read("AGENTS.md"));
    expect(section).toContain(`## @mrmeg packages\n\n${SECTION_NOTE}`);
    expect(section).toContain(`\n\n### ${UI}\n\nFirst rule.\n\n- a list item\n${END}`);
    expect(section).not.toMatch(/^# @mrmeg\/expo-ui$/m);
    expect(section.endsWith(`\n${END}`)).toBe(true);
  });

  it("lists a package that ships no llms.txt, with its docs and no body", () => {
    writeManifest([UI], [LINT]);
    install(LINT, { version: "0.1.0", llms: null, docs: ["README.md", "CHANGELOG.md"] });

    expect(agents().status).toBe(0);

    const section = sectionOf(read("AGENTS.md"));
    expect(section).toContain(`### ${LINT}\n\nDocs: \`node_modules/${LINT}/README.md\`\n`);
  });

  it("does not crash on a package with neither llms.txt nor docs", () => {
    writeManifest([UI], [LINT]);
    install(LINT, { version: "0.1.0", llms: null });

    expect(agents().status).toBe(0);

    const section = sectionOf(read("AGENTS.md"));
    expect(section).toContain(`### ${LINT}\n\nAfter UI edits`);
    expect(agents(["--check"]).status).toBe(0);
  });

  it("names only the doc files the installed version ships", () => {
    install(UI, { version: "0.9.0", docs: ["LLM_USAGE.md", "docs/components/index.md", "README.md"] });

    expect(agents().status).toBe(0);
    const section = sectionOf(read("AGENTS.md"));
    expect(section).toContain(
      `Docs: \`node_modules/${UI}/LLM_USAGE.md\`, \`node_modules/${UI}/docs/components/index.md\`, \`node_modules/${UI}/README.md\`\n`
    );
    expect(section).not.toContain("llms-full.md");

    // Once llms-full.md ships, it joins the line in its fixed place.
    install(UI, { version: "0.9.0", docs: ["LLM_USAGE.md", "llms-full.md"] });
    expect(agents().status).toBe(0);
    expect(sectionOf(read("AGENTS.md"))).toContain(`Docs: \`node_modules/${UI}/LLM_USAGE.md\`, \`node_modules/${UI}/llms-full.md\`\n`);
  });

  it("omits the Docs line when no doc ships", () => {
    install(UI, { version: "0.9.0", docs: [] });

    expect(agents().status).toBe(0);
    expect(sectionOf(read("AGENTS.md"))).not.toContain("Docs:");
  });

  it("closes with the lint instruction only when the lint plugin is installed", () => {
    expect(agents().status).toBe(0);
    expect(sectionOf(read("AGENTS.md"))).not.toContain("expo-ui-lint");

    writeManifest([UI], [LINT]);
    install(LINT, { version: "0.1.0", llms: null, docs: ["README.md"] });
    expect(agents().status).toBe(0);

    const section = sectionOf(read("AGENTS.md"));
    const closing =
      "After UI edits run `bunx expo-ui-lint --changed` (add `--base main` where the repo has no `dev` branch).";
    expect(section.endsWith(`\n\n${closing}\n${END}`)).toBe(true);
  });

  it("skips a package whose package.json has no version, and fails when nothing is left", () => {
    write(`node_modules/${UI}/package.json`, JSON.stringify({ name: UI }));

    const result = agents();
    expect(result.status).toBe(1);
    expect(result.stderr).toContain("@mrmeg/expo-ui is listed in package.json but not installed");
    expect(result.output).toContain("none of the listed @mrmeg packages is installed");
    expect(exists("AGENTS.md")).toBe(false);
  });
});

describe("expo-ui-agents --check", () => {
  it("returns 0 when fresh and 1 when the file is missing, has no section, or is stale", () => {
    const missing = agents(["--check"]);
    expect(missing.status).toBe(1);
    expect(missing.stderr).toContain("AGENTS.md is missing");
    expect(exists("AGENTS.md")).toBe(false);

    write("AGENTS.md", CONSUMER);
    const noSection = agents(["--check"]);
    expect(noSection.status).toBe(1);
    expect(noSection.stderr).toContain("AGENTS.md has no @mrmeg packages section");
    expect(read("AGENTS.md")).toBe(CONSUMER);

    expect(agents().status).toBe(0);
    const fresh = agents(["--check"]);
    expect(fresh.status).toBe(0);
    expect(fresh.stdout).toContain("AGENTS.md is up to date (@mrmeg/expo-ui@0.9.0).");

    const before = read("AGENTS.md");
    install(UI, { version: "0.9.1", docs: ["LLM_USAGE.md"] });
    const stale = agents(["--check"]);
    expect(stale.status).toBe(1);
    expect(stale.stderr).toContain("the @mrmeg packages section in AGENTS.md is stale");
    expect(stale.stderr).toContain("bunx expo-ui-agents");
    expect(read("AGENTS.md")).toBe(before);
  });

  it("detects a hand edit inside the block and a newly installed package", () => {
    expect(agents().status).toBe(0);
    write("AGENTS.md", read("AGENTS.md").replace("Installed:", "Installed (edited):"));
    expect(agents(["--check"]).status).toBe(1);

    expect(agents().status).toBe(0);
    expect(agents(["--check"]).status).toBe(0);

    writeManifest([UI, MEDIA]);
    install(MEDIA, { version: "0.7.0" });
    expect(agents(["--check"]).status).toBe(1);
  });

  it("ignores edits outside the markers", () => {
    write("AGENTS.md", CONSUMER);
    expect(agents().status).toBe(0);
    write("AGENTS.md", `${read("AGENTS.md")}\nA new note.\n`);

    expect(agents(["--check"]).status).toBe(0);
  });
});

describe("expo-ui-agents arguments", () => {
  it("rejects an unknown option, a stray argument, and a --file without a value", () => {
    expect(agents(["--chek"]).output).toContain("unknown option --chek");
    expect(agents(["--chek"]).status).toBe(1);
    expect(agents(["write"]).output).toContain("unexpected argument(s) write");
    expect(agents(["--file"]).output).toContain("--file needs a value");
    expect(agents(["--file", "--check"]).output).toContain("--file needs a value");
    expect(agents(["--check=1"]).output).toContain("unknown option --check=1");
    expect(exists("AGENTS.md")).toBe(false);
  });

  it("prints usage for --help without touching the project", () => {
    const result = agents(["--help"]);
    expect(result.status).toBe(0);
    expect(result.stdout).toContain("Usage:");
    expect(result.stdout).toContain("expo-ui-agents [--check] [--file <path>]");
    expect(exists("AGENTS.md")).toBe(false);
  });

  it("explains a missing package.json and an app that lists no @mrmeg package", () => {
    rmSync(join(project, "package.json"));
    const noManifest = agents();
    expect(noManifest.status).toBe(1);
    expect(noManifest.stderr).toContain("package.json not found");

    write("package.json", JSON.stringify({ name: "consumer", dependencies: { react: "*" } }));
    const none = agents();
    expect(none.status).toBe(1);
    expect(none.stderr).toContain("package.json lists none of @mrmeg/expo-ui");
    expect(exists("AGENTS.md")).toBe(false);
  });
});

describe("inlined size budget", () => {
  const LLMS_LIMIT_BYTES = 3 * 1024;
  const SECTION_LIMIT_BYTES = 8 * 1024;
  const workspace = [
    [UI, "ui"],
    [MEDIA, "media"],
    [PURCHASES, "purchases"],
  ] as const;

  it.each(workspace)("keeps %s's llms.txt at or under 3 KB (3072 bytes)", (_name, dir) => {
    const size = Buffer.byteLength(readFileSync(join(root, "packages", dir, "llms.txt"), "utf8"));
    expect(size).toBeLessThanOrEqual(LLMS_LIMIT_BYTES);
  });

  it("keeps the generated section for ui, media, and purchases at or under 8 KB (8192 bytes)", () => {
    // The real llms.txt and version of each workspace package, with every doc
    // file present so the Docs lines are as long as they get.
    writeManifest(workspace.map(([name]) => name));
    for (const [name, dir] of workspace) {
      const source = join(root, "packages", dir);
      const { version } = JSON.parse(readFileSync(join(source, "package.json"), "utf8")) as { version: string };
      install(name, {
        version,
        llms: readFileSync(join(source, "llms.txt"), "utf8"),
        docs: ["LLM_USAGE.md", "llms-full.md", "docs/components/index.md", "README.md"],
      });
    }

    expect(agents().status).toBe(0);

    const section = sectionOf(read("AGENTS.md"));
    for (const [name] of workspace) expect(section).toContain(`### ${name}`);
    expect(Buffer.byteLength(section)).toBeLessThanOrEqual(SECTION_LIMIT_BYTES);
  });
});
