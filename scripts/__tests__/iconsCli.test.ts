/**
 * The icon pipeline's two generators.
 *
 * `scripts/build-icon-registry.mjs` (`bun run ui:icons`) writes the package
 * builtins and the Lucide snapshot from `lucide-static`; the committed output
 * must be fresh. `packages/ui/bin/expo-ui-icons.mjs` (`bun run icons`, and the
 * `expo-ui-icons` bin consumers run) compiles an app's `client/icons.json` and
 * rasterizes its tab icons. Each CLI case runs in a throwaway project directory
 * with its own manifest; rasterizing uses a fake `rsvg-convert` through
 * `RSVG_CONVERT`, so these never need librsvg.
 */
import { execFileSync } from "child_process";
import { chmodSync, existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "fs";
import { tmpdir } from "os";
import { dirname, join } from "path";

const root = join(__dirname, "..", "..");
const cli = join(root, "packages", "ui", "bin", "expo-ui-icons.mjs");
const snapshot = JSON.parse(readFileSync(join(root, "packages", "ui", "src", "icons", "lucide.json"), "utf8")) as {
  lucide: string;
  aliases: Record<string, string>;
  icons: Record<string, unknown>;
};

type Result = { status: number; output: string };

function run(command: string, args: string[], cwd: string, env: Record<string, string> = {}): Result {
  try {
    const stdout = execFileSync(command, args, {
      cwd,
      encoding: "utf8",
      env: { ...process.env, ...env },
      stdio: ["ignore", "pipe", "pipe"],
    });
    return { status: 0, output: stdout };
  } catch (error) {
    const failure = error as { status?: number; stdout?: string; stderr?: string };
    return { status: failure.status ?? 1, output: `${failure.stdout ?? ""}${failure.stderr ?? ""}` };
  }
}

let project: string;
let fakeRasterizer: string;
const icons = (args: string[], env: Record<string, string> = {}) => run("node", [cli, ...args], project, env);
const write = (path: string, content: string) => {
  mkdirSync(dirname(join(project, path)), { recursive: true });
  writeFileSync(join(project, path), content);
};
const read = (path: string) => readFileSync(join(project, path), "utf8");
const writeManifest = (manifest: { icons: string[]; tabIcons?: string[] }) =>
  write("client/icons.json", `${JSON.stringify({ tabIcons: [], ...manifest }, null, 2)}\n`);
const withFake: Record<string, string> = { RSVG_CONVERT: "" };

beforeEach(() => {
  project = mkdtempSync(join(tmpdir(), "expo-ui-icons-test-"));
  fakeRasterizer = join(project, "fake-rsvg-convert.cjs");
  writeFileSync(
    fakeRasterizer,
    [
      "#!/usr/bin/env node",
      "const args = process.argv.slice(2);",
      'if (args.includes("--version")) { console.log("fake rsvg-convert"); process.exit(0); }',
      'require("fs").writeFileSync(args[args.indexOf("-o") + 1], `fake png ${args[args.indexOf("-w") + 1]}px`);',
      "",
    ].join("\n")
  );
  chmodSync(fakeRasterizer, 0o755);
  withFake.RSVG_CONVERT = fakeRasterizer;
});

afterEach(() => {
  rmSync(project, { recursive: true, force: true });
});

describe("build-icon-registry (ui:icons)", () => {
  it("has committed builtins, snapshot, and license that are fresh", () => {
    const result = run("node", ["scripts/build-icon-registry.mjs", "--check"], root);
    expect(result.output).toContain("up to date");
    expect(result.status).toBe(0);
  });

  it("snapshots every Lucide icon with the alias map", () => {
    expect(snapshot.lucide).toMatch(/^\d+\.\d+\.\d+$/);
    expect(Object.keys(snapshot.icons).length).toBeGreaterThan(1000);
    expect(snapshot.aliases.home).toBe("house");
    expect(snapshot.aliases["alert-circle"]).toBe("circle-alert");
    for (const canonical of Object.values(snapshot.aliases)) expect(snapshot.icons[canonical]).toBeDefined();
  });

  it("rejects an unknown argument", () => {
    expect(run("node", ["scripts/build-icon-registry.mjs", "--chek"], root).status).toBe(1);
  });
});

describe("expo-ui-icons generate", () => {
  it("writes appIcons and the IconRegistry augmentation, and --check passes on the result", () => {
    writeManifest({ icons: ["archive", "check"] });

    const result = icons([]);
    expect(result.status).toBe(0);
    expect(result.output).toContain("Wrote client/icons.generated.ts (2 icons");

    const generated = read("client/icons.generated.ts");
    expect(generated).toContain(`// GENERATED by \`bun run icons\` from client/icons.json (lucide ${snapshot.lucide}). Do not edit.`);
    expect(generated).toContain('import type { IconGlyph } from "@mrmeg/expo-ui/components/Icon";');
    expect(generated).toMatch(/^ {2}"archive": \[\["rect", \{ .*\}\]/m);
    expect(generated).toContain("} as const satisfies Record<string, IconGlyph>;");
    expect(generated).toContain('declare module "@mrmeg/expo-ui/components/Icon" {');
    expect(generated).toContain('    "archive": true;');
    // A package builtin may be listed too; the app then owns that glyph as well.
    expect(generated).toContain('    "check": true;');

    expect(icons(["--check"]).status).toBe(0);
  });

  it("fails --check when the module is missing or stale, and writes nothing", () => {
    writeManifest({ icons: ["archive"] });
    const missing = icons(["--check"]);
    expect(missing.status).toBe(1);
    expect(missing.output).toContain("client/icons.generated.ts is missing");
    expect(existsSync(join(project, "client/icons.generated.ts"))).toBe(false);

    expect(icons([]).status).toBe(0);
    writeManifest({ icons: ["archive", "bell"] });
    const stale = icons(["--check"]);
    expect(stale.status).toBe(1);
    expect(stale.output).toContain("client/icons.generated.ts is stale");
  });

  it("rejects an unknown name", () => {
    writeManifest({ icons: ["not-a-lucide-icon"] });
    const result = icons([]);
    expect(result.status).toBe(1);
    expect(result.output).toContain(`"not-a-lucide-icon" is not a Lucide ${snapshot.lucide} icon`);
  });

  it("rejects an alias with the canonical name", () => {
    writeManifest({ icons: ["home"] });
    const result = icons([]);
    expect(result.status).toBe(1);
    expect(result.output).toContain("home → house");
  });

  it("rejects an unsorted or duplicated list", () => {
    writeManifest({ icons: ["bell", "archive"] });
    expect(icons([]).output).toContain('"icons" must be sorted');
    writeManifest({ icons: ["archive", "archive"] });
    expect(icons([]).output).toContain("lists the same name twice: archive");
  });

  it("honors --manifest, --out, and --module", () => {
    write("icons/list.json", `${JSON.stringify({ icons: ["bell"] })}\n`);
    const result = icons(["--manifest", "icons/list.json", "--out", "src/glyphs.ts", "--module", "@acme/ui/Icon"]);
    expect(result.status).toBe(0);
    const generated = read("src/glyphs.ts");
    expect(generated).toContain("from icons/list.json");
    expect(generated).toContain('import type { IconGlyph } from "@acme/ui/Icon";');
    expect(generated).toContain('declare module "@acme/ui/Icon" {');
  });
});

describe("expo-ui-icons add", () => {
  it("inserts names sorted, canonicalizes an alias with a notice, and regenerates", () => {
    writeManifest({ icons: ["check"] });
    const result = icons(["add", "zap", "home", "archive"]);
    expect(result.status).toBe(0);
    expect(result.output).toContain("home → house");
    expect(JSON.parse(read("client/icons.json")).icons).toEqual(["archive", "check", "house", "zap"]);
    expect(icons(["--check"]).status).toBe(0);
  });

  it("canonicalizes Lucide aliases that have their own font codepoints", () => {
    writeManifest({ icons: ["check"] });
    const result = icons(["add", "trash-2", "flip-horizontal"]);
    expect(result.status).toBe(0);
    expect(result.output).toContain("trash-2 → trash");
    expect(JSON.parse(read("client/icons.json")).icons).toEqual([
      "check",
      "square-centerline-dashed-horizontal",
      "trash",
    ]);
  });

  it("fails on an unknown name without touching the manifest", () => {
    writeManifest({ icons: ["check"] });
    const before = read("client/icons.json");
    const result = icons(["add", "archive", "nope-not-an-icon"]);
    expect(result.status).toBe(1);
    expect(result.output).toContain('"nope-not-an-icon" is not a Lucide');
    expect(read("client/icons.json")).toBe(before);
  });
});

describe("expo-ui-icons init", () => {
  it("seeds the manifest from icon literals, skipping tests, generated files, and aliases", () => {
    write("app/index.tsx", '<Icon name="archive" />\n<ItemMedia icon={"bell"} />\n');
    write("client/nav.ts", 'export const tabs = [{ name: "home", icon: "zap" }, { name: "index" }];\n');
    write("shared/menu.ts", 'const item = { icon : "star" };\n');
    write("client/__tests__/nav.test.tsx", '<Icon name="camera" />\n');
    write("client/thing.test.ts", '<Icon name="mic" />\n');
    write("client/old.generated.ts", '<Icon name="video" />\n');

    const result = icons(["init"]);
    expect(result.status).toBe(0);
    expect(result.output).toContain("home → house");
    expect(JSON.parse(read("client/icons.json"))).toEqual({ icons: ["archive", "bell", "star", "zap"], tabIcons: [] });
    expect(read("client/icons.generated.ts")).toContain('    "zap": true;');
  });

  it("refuses to overwrite an existing manifest without --force", () => {
    writeManifest({ icons: ["check"], tabIcons: ["check"] });
    write("app/index.tsx", '<Icon name="archive" />\n');

    const refused = icons(["init"]);
    expect(refused.status).toBe(1);
    expect(refused.output).toContain("--force");

    expect(icons(["init", "--force"]).status).toBe(0);
    // An overwritten manifest keeps its tab icons, which stay in "icons".
    expect(JSON.parse(read("client/icons.json"))).toEqual({ icons: ["archive", "check"], tabIcons: ["check"] });
  });
});

describe("expo-ui-icons tabs", () => {
  beforeEach(() => {
    writeManifest({ icons: ["compass", "settings", "user"], tabIcons: ["compass", "user"] });
  });

  it("rasterizes 1x/2x/3x PNGs, records hashes, writes the require module, and --check passes", () => {
    const result = icons(["tabs"], withFake);
    expect(result.status).toBe(0);

    for (const name of ["compass", "user"]) {
      expect(read(`assets/icons/tabs/${name}.png`)).toBe("fake png 24px");
      expect(read(`assets/icons/tabs/${name}@2x.png`)).toBe("fake png 48px");
      expect(read(`assets/icons/tabs/${name}@3x.png`)).toBe("fake png 72px");
    }
    const recorded = JSON.parse(read("assets/icons/tabs/manifest.json"));
    expect(recorded.lucide).toBe(snapshot.lucide);
    expect(Object.keys(recorded.icons)).toEqual(["compass", "user"]);
    expect(recorded.icons.compass).toMatch(/^[0-9a-f]{64}$/);

    const module = read("client/tabIcons.generated.ts");
    expect(module).toContain('  compass: require("../assets/icons/tabs/compass.png"),');
    expect(module).toContain("export type TabIconName = keyof typeof TAB_ICONS;");

    expect(icons(["tabs", "--check"]).status).toBe(0);
  });

  it("--check detects a hash mismatch, a missing PNG, and a stale module without rasterizing", () => {
    expect(icons(["tabs"], withFake).status).toBe(0);

    const recordedPath = "assets/icons/tabs/manifest.json";
    const recorded = JSON.parse(read(recordedPath));
    recorded.icons.user = "0".repeat(64);
    write(recordedPath, `${JSON.stringify(recorded, null, 2)}\n`);
    rmSync(join(project, "assets/icons/tabs/compass@3x.png"));
    write("client/tabIcons.generated.ts", "// edited\n");

    const result = icons(["tabs", "--check"], withFake);
    expect(result.status).toBe(1);
    expect(result.output).toContain("user: hash mismatch");
    expect(result.output).toContain("assets/icons/tabs/compass@3x.png is missing");
    expect(result.output).toContain("client/tabIcons.generated.ts is stale");
    expect(existsSync(join(project, "assets/icons/tabs/compass@3x.png"))).toBe(false);
  });

  it("--check fails when the snapshot version moved", () => {
    expect(icons(["tabs"], withFake).status).toBe(0);
    const recorded = JSON.parse(read("assets/icons/tabs/manifest.json"));
    write("assets/icons/tabs/manifest.json", `${JSON.stringify({ ...recorded, lucide: "0.0.1" }, null, 2)}\n`);
    const result = icons(["tabs", "--check"]);
    expect(result.status).toBe(1);
    expect(result.output).toContain("rendered from lucide 0.0.1");
  });

  it("skips rasterizing with a clear message when fresh, even without rsvg-convert", () => {
    expect(icons(["tabs"], withFake).status).toBe(0);
    const result = icons(["tabs"], { RSVG_CONVERT: join(project, "no-such-rsvg-convert") });
    expect(result.status).toBe(0);
    expect(result.output).toContain("nothing to rasterize");
  });

  it("fails with the librsvg hint when stale and rsvg-convert is absent", () => {
    const result = icons(["tabs"], { RSVG_CONVERT: join(project, "no-such-rsvg-convert") });
    expect(result.status).toBe(1);
    expect(result.output).toContain("rsvg-convert was not found");
    expect(result.output).toContain("brew install librsvg");
    expect(existsSync(join(project, "assets/icons/tabs/manifest.json"))).toBe(false);
  });

  it("removes PNGs of a name dropped from tabIcons", () => {
    expect(icons(["tabs"], withFake).status).toBe(0);
    writeManifest({ icons: ["compass", "settings", "user"], tabIcons: ["compass"] });
    expect(icons(["tabs", "--check"]).output).toContain('user: rendered but no longer in "tabIcons"');
    expect(icons(["tabs"], withFake).status).toBe(0);
    expect(existsSync(join(project, "assets/icons/tabs/user.png"))).toBe(false);
    expect(Object.keys(JSON.parse(read("assets/icons/tabs/manifest.json")).icons)).toEqual(["compass"]);
    expect(icons(["tabs", "--check"]).status).toBe(0);
  });

  it("requires every tab icon to be in icons", () => {
    writeManifest({ icons: ["compass"], tabIcons: ["compass", "user"] });
    const result = icons(["tabs"], withFake);
    expect(result.status).toBe(1);
    expect(result.output).toContain('every "tabIcons" name must also be in "icons" (missing: user)');
  });
});

describe("expo-ui-icons arguments", () => {
  it("rejects an unknown option and stray arguments", () => {
    writeManifest({ icons: [] });
    expect(icons(["--chek"]).output).toContain("unknown option --chek");
    expect(icons(["generate", "extra"]).output).toContain("unexpected argument(s) extra");
    expect(icons(["init", "--check"]).output).toContain("--check does not apply to init");
  });

  it("explains a missing manifest", () => {
    const result = icons([]);
    expect(result.status).toBe(1);
    expect(result.output).toContain("client/icons.json not found");
  });
});
