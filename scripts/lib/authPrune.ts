/**
 * Auth-provider pruning for `bun run init`.
 *
 * The template carries two auth SDK clusters (Clerk, Amplify/Cognito) and an
 * app only ever selects one, so init removes the packages of every provider the
 * fork does not use and swaps that provider's implementation modules for typed
 * stubs. Importers, the `import()` split points, and `tsc` keep working
 * untouched: `getAuthProvider()` reads env, init writes only the chosen
 * provider's env, so a stub's factory never runs in a correctly configured app.
 * If env does select a pruned provider, the stub throws a message saying how to
 * restore it.
 *
 * Everything here is pure (strings in, strings out) except `applyAuthPrune`,
 * which takes the project root and is idempotent: stubs carry a sentinel,
 * package removal and file deletion are no-ops the second time.
 */

import * as fs from "node:fs";
import * as path from "node:path";

export type AuthProvider = "clerk" | "cognito";
export type AuthSelection = AuthProvider | "none";

/** First line of every generated stub; also how re-runs recognise one. */
export const AUTH_STUB_MARKER = "@init-auth-stub";

export interface AuthStub {
  /** Repo-relative, POSIX path of the module the stub replaces. */
  path: string;
  content: string;
}

export interface AuthPruneSpec {
  provider: AuthProvider;
  label: string;
  /** `package.json` dependencies only this provider needs. */
  packages: string[];
  /** Implementation modules replaced by stubs. */
  stubs: AuthStub[];
  /** Tests that exercise the real SDK or implementation; deleted. */
  tests: string[];
}

const PROVIDER_DIR = "client/features/auth/provider";
const SERVER_DIR = "server/api/shared";

function stubMessage(label: string, selectedBy: string, restore: string): string {
  return (
    `${label} auth is not installed in this fork: \`bun run init\` removed it. ` +
    `${selectedBy} selected it; unset those variables to turn auth off or use the provider this fork ` +
    `kept. To bring ${label} back, restore ${restore} from the template and add its packages ` +
    "to package.json."
  );
}

function header(provider: AuthProvider, what: string): string {
  return (
    `// ${AUTH_STUB_MARKER} ${provider}\n` +
    `// Generated by \`bun run init\`: ${what} was removed because this fork does not use it.\n` +
    "// Importers and the dynamic import() split points still resolve; nothing selects this\n" +
    "// provider, so these exports never run in a correctly configured app.\n"
  );
}

