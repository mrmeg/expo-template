/**
 * What each provider owns.
 *
 * Packages stay in `package.json` when anything else needs them: the
 * server-side `@clerk/backend` and `aws-jwt-verify` go with their provider
 * (their verifiers are stubbed too), while `@react-native-async-storage/*`,
 * `expo-web-browser`, `expo-secure-store`, and `expo-linking` are used by the
 * app, billing, or an `app.config.ts` plugin and are never removed.
 */
export function authPruneSpec(provider: AuthProvider): AuthPruneSpec {
  if (provider === "clerk") {
    return {
      provider,
      label: "Clerk",
      packages: ["@clerk/clerk-expo", "@clerk/backend", "expo-auth-session", "expo-crypto"],
      stubs: clerkStubs(),
      tests: [
        `${PROVIDER_DIR}/__tests__/clerkClient.test.ts`,
        `${PROVIDER_DIR}/__tests__/ClerkProviderBoundary.test.tsx`,
        `${PROVIDER_DIR}/__tests__/clerkStartup.test.ts`,
        `${PROVIDER_DIR}/__tests__/AuthProviderGate.test.tsx`,
        `${SERVER_DIR}/__tests__/clerkTokenVerifier.test.ts`,
      ],
    };
  }
  return {
    provider,
    label: "Cognito",
    packages: [
      "aws-amplify",
      "@aws-amplify/react-native",
      "@aws-amplify/rtn-web-browser",
      "aws-jwt-verify",
      "react-native-get-random-values",
    ],
    stubs: cognitoStubs(),
    tests: [
      `${PROVIDER_DIR}/__tests__/cognitoClient.test.ts`,
      "client/features/auth/__tests__/cognitoSdk.guardrail.test.ts",
      `${SERVER_DIR}/__tests__/cognitoTokenVerifier.test.ts`,
    ],
  };
}

/** Providers to prune for a chosen auth setting: every one that is not chosen. */
export function providersToPrune(auth: AuthSelection, keepSdks: boolean): AuthProvider[] {
  if (keepSdks) return [];
  return (["clerk", "cognito"] as const).filter((provider) => provider !== auth);
}

export interface PackageRemoval {
  content: string;
  /** Names that were present and are now gone, in `package.json` order. */
  removed: string[];
}

const DEPENDENCY_FIELDS = [
  "dependencies",
  "devDependencies",
  "peerDependencies",
  "optionalDependencies",
] as const;

/**
 * Drop `names` from every dependency block of a `package.json` source.
 * Re-serialised with two-space indent and a trailing newline, the file's own
 * format, so an unchanged manifest comes back byte-identical.
 */
export function removePackagesFromManifest(source: string, names: string[]): PackageRemoval {
  const manifest = JSON.parse(source) as Record<string, Record<string, string> | undefined>;
  const removed: string[] = [];
  for (const field of DEPENDENCY_FIELDS) {
    const block = manifest[field];
    if (!block) continue;
    for (const name of Object.keys(block)) {
      if (!names.includes(name)) continue;
      delete block[name];
      if (!removed.includes(name)) removed.push(name);
    }
  }
  return { content: `${JSON.stringify(manifest, null, 2)}\n`, removed };
}

/** True when a module's source is one of this file's generated stubs. */
export function isAuthStub(content: string, provider?: AuthProvider): boolean {
  const firstLine = content.split("\n", 1)[0] ?? "";
  const match = new RegExp(`^// ${AUTH_STUB_MARKER} (clerk|cognito)\\s*$`).exec(firstLine);
  return match !== null && (provider === undefined || match[1] === provider);
}

export interface AuthPruneResult {
  provider: AuthProvider;
  label: string;
  packagesRemoved: string[];
  stubbed: string[];
  deleted: string[];
}

/**
 * Prune `providers` from the project at `projectRoot`. Missing files and
 * absent packages are skipped, and a stub already in place is left alone, so a
 * second run reports nothing to do.
 */
export function applyAuthPrune(projectRoot: string, providers: AuthProvider[]): AuthPruneResult[] {
  const manifestPath = path.join(projectRoot, "package.json");
  return providers.map((provider) => {
    const spec = authPruneSpec(provider);

    const removal = removePackagesFromManifest(fs.readFileSync(manifestPath, "utf8"), spec.packages);
    if (removal.removed.length > 0) fs.writeFileSync(manifestPath, removal.content);

    const stubbed: string[] = [];
    for (const stub of spec.stubs) {
      const target = path.join(projectRoot, stub.path);
      if (!fs.existsSync(target)) continue;
      if (isAuthStub(fs.readFileSync(target, "utf8"))) continue;
      fs.writeFileSync(target, stub.content);
      stubbed.push(stub.path);
    }

    const deleted: string[] = [];
    for (const test of spec.tests) {
      const target = path.join(projectRoot, test);
      if (!fs.existsSync(target)) continue;
      fs.rmSync(target);
      deleted.push(test);
    }

    return {
      provider,
      label: spec.label,
      packagesRemoved: removal.removed,
      stubbed,
      deleted,
    };
  });
}

/** Whether an earlier init already replaced `provider`'s client with a stub. */
export function isProviderPruned(projectRoot: string, provider: AuthProvider): boolean {
  const client = authPruneSpec(provider).stubs[0];
  const target = path.join(projectRoot, client.path);
  return fs.existsSync(target) && isAuthStub(fs.readFileSync(target, "utf8"), provider);
}
